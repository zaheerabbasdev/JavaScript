//Arithmatic Operators
let a = 10;

let b = 50;

console.log(a + b);

console.log(a - b);

console.log(a * b);

console.log(a / b);

console.log(a % b);

// Unary Operators

let num1 = 10;

let num2 = 5;

console.log(num1++);

console.log(++num1);

// Assignment Operators

let age1 = 20;

let age2 = 50;

age1 = age2;

console.log(age1);
